export type CopyKey = keyof typeof COPY.en;
export function t(language: Language, key: CopyKey, vars?: Record<string, string | number>): string {
  let value: string = COPY[language][key];
  for (const [name, replacement] of Object.entries(vars ?? {})) value = value.replace(`{${name}}`, String(replacement));
  return value;
}
